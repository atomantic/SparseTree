CREATE OR REPLACE VIEW person_computed AS
SELECT
    person.person_id,
    person.display_name,
    person.gender,
    birth.date_year AS birth_year,
    birth.place_original AS birth_place,
    death.date_year AS death_year,
    death.place_original AS death_place,
    death.cause AS death_cause,
    CASE
        WHEN birth.date_year IS NOT NULL AND death.date_year IS NOT NULL
        THEN death.date_year - birth.date_year
    END AS age_at_death,
    (SELECT COUNT(*) FROM parent_edge WHERE parent_id = person.person_id) AS child_count,
    (SELECT MIN(date_year) FROM life_event
     WHERE person_id = person.person_id AND event_type = 'http://gedcomx.org/Marriage') AS first_marriage_year,
    CASE
        WHEN birth.date_year IS NOT NULL THEN
            (SELECT MIN(date_year) FROM life_event
             WHERE person_id = person.person_id AND event_type = 'http://gedcomx.org/Marriage') - birth.date_year
    END AS age_at_first_marriage,
    (SELECT value FROM life_event
     WHERE person_id = person.person_id AND event_type = 'data:,TitleOfNobility'
     ORDER BY created_at, event_id LIMIT 1) AS title_of_nobility,
    (SELECT value FROM life_event
     WHERE person_id = person.person_id AND event_type = 'http://gedcomx.org/Occupation'
     ORDER BY created_at, event_id LIMIT 1) AS primary_occupation,
    (SELECT value FROM life_event
     WHERE person_id = person.person_id AND event_type = 'http://gedcomx.org/MilitaryService'
     ORDER BY created_at, event_id LIMIT 1) AS military_service,
    EXISTS (
        SELECT 1 FROM note
        WHERE person_id = person.person_id AND note_type = 'life_sketch'
    ) AS has_life_sketch
FROM person
LEFT JOIN LATERAL (
    SELECT date_year, place_original
    FROM life_event
    WHERE person_id = person.person_id AND event_type = 'http://gedcomx.org/Birth'
    ORDER BY created_at, event_id
    LIMIT 1
) AS birth ON TRUE
LEFT JOIN LATERAL (
    SELECT date_year, place_original, cause
    FROM life_event
    WHERE person_id = person.person_id AND event_type = 'http://gedcomx.org/Death'
    ORDER BY created_at, event_id
    LIMIT 1
) AS death ON TRUE;

CREATE OR REPLACE FUNCTION sparsetree_set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

DO $trigger$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname = 'trg_person_updated_at'
          AND tgrelid = 'person'::REGCLASS
    ) THEN
        CREATE TRIGGER trg_person_updated_at
        BEFORE UPDATE ON person
        FOR EACH ROW EXECUTE FUNCTION sparsetree_set_updated_at();
    END IF;
END
$trigger$;

DO $trigger$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname = 'trg_life_event_updated_at'
          AND tgrelid = 'life_event'::REGCLASS
    ) THEN
        CREATE TRIGGER trg_life_event_updated_at
        BEFORE UPDATE ON life_event
        FOR EACH ROW EXECUTE FUNCTION sparsetree_set_updated_at();
    END IF;
END
$trigger$;

DO $trigger$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname = 'trg_note_updated_at'
          AND tgrelid = 'note'::REGCLASS
    ) THEN
        CREATE TRIGGER trg_note_updated_at
        BEFORE UPDATE ON note
        FOR EACH ROW EXECUTE FUNCTION sparsetree_set_updated_at();
    END IF;
END
$trigger$;

DO $trigger$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname = 'trg_local_override_updated_at'
          AND tgrelid = 'local_override'::REGCLASS
    ) THEN
        CREATE TRIGGER trg_local_override_updated_at
        BEFORE UPDATE ON local_override
        FOR EACH ROW EXECUTE FUNCTION sparsetree_set_updated_at();
    END IF;
END
$trigger$;

CREATE OR REPLACE FUNCTION sparsetree_touch_database_info()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE database_info
    SET updated_at = CURRENT_TIMESTAMP
    WHERE db_id = NEW.db_id;
    RETURN NEW;
END;
$$;

DO $trigger$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname = 'trg_database_membership_insert'
          AND tgrelid = 'database_membership'::REGCLASS
    ) THEN
        CREATE TRIGGER trg_database_membership_insert
        AFTER INSERT ON database_membership
        FOR EACH ROW EXECUTE FUNCTION sparsetree_touch_database_info();
    END IF;
END
$trigger$;
