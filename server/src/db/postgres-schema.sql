    person_id TEXT PRIMARY KEY REFERENCES person(person_id) ON DELETE CASCADE,
    display_name TEXT NOT NULL,
    birth_name TEXT NOT NULL DEFAULT '',
    aliases TEXT NOT NULL DEFAULT '',
